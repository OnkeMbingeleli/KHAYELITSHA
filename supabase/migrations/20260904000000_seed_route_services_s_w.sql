-- Register pickup/drop-off route services and their timetable numbers.
-- A route pair may have more than one timetable number, so these are kept
-- separately from the destination routes used by the operational screens.
CREATE TABLE IF NOT EXISTS public.route_services (
  id UUID PRIMARY KEY DEFAULT gen_random_uuid(),
  branch_id UUID NOT NULL REFERENCES public.branches(id) ON DELETE CASCADE,
  pickup_point TEXT NOT NULL,
  dropoff_point TEXT NOT NULL,
  timetable_number TEXT NOT NULL,
  created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
  UNIQUE (branch_id, pickup_point, dropoff_point, timetable_number)
);

